<script>
    let isRecoveryMode = false;

    function toggleRecoveryMode() {
        isRecoveryMode = !isRecoveryMode;
        const codeInput = document.getElementById('code');
        const codeLabel = document.getElementById('code-label');
        const toggleLink = document.getElementById('toggleRecoveryLink');
        const desc = document.getElementById('method-description');

        if (isRecoveryMode) {
            codeLabel.innerText = "Backup Recovery Code";
            codeInput.placeholder = "XXXXX-XXXXX";
            codeInput.setAttribute('maxlength', '11');
            codeInput.setAttribute('inputmode', 'text');
            codeInput.value = '';
            toggleLink.innerText = "Use 6-digit Authenticator Code";
            desc.innerText = "Enter one of the 8 single-use recovery codes generated when you set up 2FA.";
        } else {
            codeLabel.innerText = "Verification Code";
            codeInput.placeholder = "000 000";
            codeInput.setAttribute('maxlength', '6');
            codeInput.setAttribute('inputmode', 'numeric');
            codeInput.value = '';
            toggleLink.innerText = "Use a Backup Recovery Code";
            desc.innerText = "Enter the 6-digit security code generated by your Authenticator app or sent to your email.";
        }
        codeInput.focus();
    }

    // Auto-advance or auto-submit on 6 numeric digits
    document.getElementById('code').addEventListener('input', function(e) {
        if (!isRecoveryMode) {
            let val = this.value.replace(/\D/g, '');
            if (val.length > 6) val = val.substring(0, 6);
            this.value = val;
            if (val.length === 6) {
                document.getElementById('twoFactorForm').submit();
            }
        }
    });

    // Cooldown timer if resend countdown active
    let cooldown = {{ $cooldown ?? 0 }};
    if (cooldown > 0) {
        const resendBtn = document.getElementById('resendBtn');
        const resendText = document.getElementById('resendText');
        const timer = setInterval(() => {
            cooldown--;
            if (resendText) resendText.innerText = `Resend in ${cooldown}s`;
            if (cooldown <= 0) {
                clearInterval(timer);
                if (resendBtn) resendBtn.removeAttribute('disabled');
                if (resendText) resendText.innerText = 'Resend Email Code';
            }
        }, 1000);
    }
</script>
